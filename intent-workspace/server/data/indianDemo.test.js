import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { generateSeed, CLIENT_INDEX } from './seedData.js';
import { localizeDemo } from './indianDemo.js';
import { localizationPlan } from './localizeStoredDemo.js';
import { buildPayload } from './payload.js';
import { detectClient } from '../intent.js';
const now = new Date('2026-10-11T10:00:00Z'), old = generateSeed(now, false), indian = generateSeed(now);
assert.equal(indian.clients[0].name, 'Bharat Logistics');
assert.equal(indian.tasks[0].title, 'Integrate UPI payment webhooks');
assert.equal(indian.tasks[2].owner, 'Meera');
assert.equal(CLIENT_INDEX.find(c => c.id === 'kestrel').name, 'Aarogya Healthcare');
assert.equal(detectClient('Prepare the Aarogya meeting'), 'kestrel');
assert.equal(indian.clients[0].currency, 'INR');
assert.match(buildPayload(indian, 'kestrel', now).client[0].text, /₹240 lakh/);
assert.deepEqual(localizeDemo(indian), indian);
const key = t => createHash('sha256').update(JSON.stringify([t.clientId ?? '', t.title ?? '', t.owner ?? ''])).digest('hex').slice(0, 20);
const custom = { _id: 'custom', title: 'Fix login issue', owner: 'ankit', status: 'in_progress', createdAt: now };
const snapshot = { tasks: [{ _id: 'demo', ...old.tasks[0] }, custom], goals: [{ _id: 'goal', taskKeys: [key(old.tasks[0]), 'custom-key'] }] };
const plan = localizationPlan(snapshot);
assert.equal(plan.filter(p => p.collection === 'iw_tasks').length, 1);
assert.ok(!plan.some(p => p.id === 'custom'));
assert.deepEqual(plan.find(p => p.collection === 'iw_goals').values.taskKeys, [key(indian.tasks[0]), 'custom-key']);
assert.equal(snapshot.tasks[1], custom);
console.log('Indian demo aliases, rupee display, preserved tasks and goal links checks passed.');
